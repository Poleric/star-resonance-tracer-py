from star_resonance_tracer.msg import NotifyMsg
from star_resonance_tracer.processor import process_bytes
from star_resonance_tracer.proto.serv_chit_chat_ntf_pb2 import ChitChatNtf

DATA = bytearray(
    [
        0x0, 0x0, 0x0, 0x42,  # packet size
        0x0, 0x2,  # frame_type: notify
        0x0, 0x0, 0x0, 0x0, 0x9, 0xd4, 0xa7, 0x68,  # service uuid
        0x0, 0x0, 0x0, 0x0,  # stub_id
        0x0, 0x0, 0x0, 0x1,  # method_id

        0xa, 0x2a, 0x8, 0x1, 0x12, 0x26, 0x8, 0x8e, 0x9f, 0x3f, 0x12, 0x12, 0x8, 0x98, 0xd1, 0xc, 0x12, 0x6, 0x43, 0x68,
        0x61, 0x77, 0x65, 0x65, 0x18, 0x1, 0x20, 0x1, 0x28, 0x3c, 0x18, 0x9d, 0xe2, 0xd6, 0xcc, 0x6, 0x22, 0x6, 0x1a,
        0x4, 0x4d, 0x63, 0x31, 0x36
    ]
)

CHIT_CHAT_NTF_SERVICE = 0x9d4a768
CHIT_CHAT_NTF_NOTIFY_NEWEST_CHIT_CHAT_MSGS_METHOD = 0x1

if __name__ == '__main__':
    for msg in process_bytes(DATA):
        if isinstance(msg, NotifyMsg) \
                and msg.service_uuid == CHIT_CHAT_NTF_SERVICE \
                and msg.method_id == CHIT_CHAT_NTF_NOTIFY_NEWEST_CHIT_CHAT_MSGS_METHOD:
            print(ChitChatNtf.NotifyNewestChitChatMsgs.FromString(msg.data))  # noqa
